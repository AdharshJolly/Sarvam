class GlossaryEntry(BaseModel):
    label: str  # short plain-English name shown on chips and headings
    meaning: str  # one sentence: what this result means
    next_step: str  # one sentence: what a reader can do about it ("" when nothing is needed)


def _e(label: str, meaning: str, next_step: str = "") -> GlossaryEntry:
    return GlossaryEntry(label=label, meaning=meaning, next_step=next_step)


