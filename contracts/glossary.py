"""Plain-language glossary (decision B-36): the single source of user-facing wording.

Every enum value a reader can see (coverage state, final state, verdict, challenge outcome, conflict
kind and status, stop reason, failure, source status, certainty) maps to a plain label, a one-line
meaning and a next step. The frontend reads `contracts/generated/glossary.ts` (generated by
`contracts/schema_export.py`) and the Markdown report renderer reads this module, so the two can
never drift. Stored values and enum names do not change; only what people read does.

The headline labels for `final_state` and `coverage_state` are fixed by the project owner; a test
pins them. A missing entry for any enum value fails `tests/unit/test_glossary.py`.
"""

