def gap_text(state: str, origins: int, claims: int, conflicts: int) -> GapText:
    """Plain-English reason and next step for one non-green coverage cell.

    Built only from stored cell fields (no parsing of the raw reason string), and the next step is
    borrowed from the matching glossary entry, so wording stays in one place.
    """
    cov = GLOSSARY["coverage_state"].get(state)
    if cov is None:
        raise KeyError(f"coverage_state.{state}")
    outcome = cov.label.lower()
    if claims == 0 and origins == 0 and conflicts == 0:
        why, step = "no usable evidence was found", cov.next_step
    elif conflicts > 0:
        why = "sources disagree and the difference is not yet explained"
        step = GLOSSARY["conflict_status"][ConflictStatus.OPEN.value].next_step
    elif origins <= 1:
        why = "only one independent source"
        step = GLOSSARY["certainty"][CertaintyLabel.SINGLE_ORIGIN.value].next_step
    else:
        why, step = "the sources found only partly back this point", cov.next_step
    return GapText(
        reason=f"{why}, so {'it is ' if state == 'AMBER' else 'there is '}{outcome}", next_step=step
    )


def entry(table: str, value: str) -> GlossaryEntry:
    """Lookup used by the backend; raises KeyError for an unknown value so a gap is never silent."""
    return GLOSSARY[table][value]


def label(table: str, value: str) -> str:
    return entry(table, value).label


def glossary_ts() -> str:
    """Render the glossary as a TypeScript module (generated; never hand-edited)."""
    import json

    lines = [
        "/* GENERATED by `make contracts` from contracts/glossary.py.",
        " * Source of truth: contracts/glossary.py. DO NOT EDIT BY HAND. */",
        "",
        "export interface GlossaryEntry {",
        "  label: string;",
        "  meaning: string;",
        "  next_step: string;",
        "}",
        "",
        "export const GLOSSARY = "
        + json.dumps(
            {t: {k: v.model_dump() for k, v in rows.items()} for t, rows in GLOSSARY.items()},
            indent=2,
            ensure_ascii=False,
        )
        + " as const satisfies Record<string, Record<string, GlossaryEntry>>;",
        "",
        "export type GlossaryTable = keyof typeof GLOSSARY;",
        "",
        "export interface TermEntry {",
        "  singular: string;",
        "  plural: string;",
        "  meaning: string;",
        "}",
        "",
        "export const TERMS = "
        + json.dumps({k: v.model_dump() for k, v in TERMS.items()}, indent=2, ensure_ascii=False)
        + " as const satisfies Record<string, TermEntry>;",
        "",
        "export type TermName = keyof typeof TERMS;",
        "",
        "/** Parity fixtures: lib/gap.ts must produce these reasons (tested). */",
        "export const GAP_CASES = "
        + json.dumps(GAP_CASES, indent=2, ensure_ascii=False)
        + " as const;",
        "",
        "export const READING_GUIDE: readonly string[] = "
        + json.dumps(READING_GUIDE, indent=2, ensure_ascii=False)
        + ";",
        "",
    ]
    return "\n".join(lines)
